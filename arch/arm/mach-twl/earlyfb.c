// arch/arm/mach-twl/earlyfb.c - Nintendo TWL (DSi) sub-screen early framebuffer.
//
// Drives the bottom LCD in mode-5 8bpp extended-rotation-bitmap so kernel
// messages are visible on-screen (or in a melonDS frame capture) before a
// real fbcon/tty driver is ready.  The framebuffer is set up before C land
// starts (called from head-dsi.S) so the DEBUG_LL printascii path works from
// the very first printk in start_kernel.
//
// Public API (declared in twl-earlyfb.h):
//   void twl_early_fb_init(void)       - called once from .init_early
//   void twl_early_putc(int c)         - called per-char from debug/twl.S
//   void twl_early_fb_shutdown(void)   - called by twl-fb when fbcon takes over

#include "twl-earlyfb.h"
#include <linux/io.h>
#include <linux/types.h>

/* ---- DSi sub-screen MMIO ------------------------------------------------ */
#define TWL_VRAMCNT_C		0x04000242u /* VRAM bank C routing (8-bit)    */
#define TWL_DISPCNT_SUB		0x04001000u /* sub-engine display ctrl (32-bit)*/
#define TWL_BG2CNT_SUB		0x0400100Cu /* sub-engine BG2 control (16-bit) */
/* BG2 affine matrix - extended rotation BG needs explicit identity or
 * PA/PD default to 0 and the background collapses to a single point. */
#define TWL_BG2PA_SUB		0x04001020u /* horizontal pixel increment, 8.8 fp */
#define TWL_BG2PB_SUB		0x04001022u /* horizontal line increment,  8.8 fp */
#define TWL_BG2PC_SUB		0x04001024u /* vertical pixel increment,   8.8 fp */
#define TWL_BG2PD_SUB		0x04001026u /* vertical line increment,    8.8 fp */
#define TWL_BG2X_SUB		0x04001028u /* reference point X, 20.8 fp, 32-bit */
#define TWL_BG2Y_SUB		0x0400102Cu /* reference point Y, 20.8 fp, 32-bit */
#define TWL_BGPAL_SUB		0x05000400u /* sub-engine BG palette base (16-bit)*/
#define TWL_VRAM_C		0x06200000u /* VRAM bank C mapped to sub BG       */

/* VRAMCNT_C: enable (bit 7) + MST=4 (bits 2:0) -> sub-engine BG */
#define VRAMCNT_C_SUB_BG	0x84u
/* DISPCNT_SUB: mode 5 | BG2 on | display=graphics */
#define DISPCNT_VAL		(5u | (1u << 10) | (1u << 16))
/* BG2CNT: 8bpp extended-rotation bitmap, 256x256 */
#define BG2CNT_BMP8_256x256	0x4080u
/* Palette index 1 = white (BGR555) */
#define PAL_WHITE		0x7FFFu

/* ---- Framebuffer geometry ------------------------------------------------ */
#define FB_W	256
#define FB_H	192
#define FONT_W	8
#define FONT_H	8
#define COLS	(FB_W / FONT_W)	/* 32 columns */
#define ROWS	(FB_H / FONT_H)	/* 24 rows    */

/* ---- Driver state -------------------------------------------------------- */
static int twl_col;
static int twl_row;
static bool twl_fb_ready;

